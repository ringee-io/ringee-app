import {
  cp,
  mkdir,
  readFile,
  readdir,
  realpath,
  rm,
  stat,
  symlink,
} from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const [appPath, runtimeRoot, ...extraArguments] = process.argv.slice(2);
if (
  !["apps/backend", "apps/orchestrator"].includes(appPath) ||
  !runtimeRoot ||
  !isAbsolute(runtimeRoot) ||
  extraArguments.length > 0
) {
  throw new Error(
    "Usage: node scripts/prepare-service-runtime.mjs apps/backend|apps/orchestrator /absolute/runtime-root",
  );
}

const sourceRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const destinationRoot = await realpath(runtimeRoot);
const sourceWithinDestination = relative(destinationRoot, sourceRoot);
if (
  sourceWithinDestination === "" ||
  (!sourceWithinDestination.startsWith(`..${sep}`) &&
    sourceWithinDestination !== ".." &&
    !isAbsolute(sourceWithinDestination))
) {
  throw new Error("Runtime root must not contain the source workspace");
}

const readManifest = async (path) => JSON.parse(await readFile(path, "utf8"));
const assertRuntimePath = (path, label) => {
  const pathWithinRuntime = relative(destinationRoot, path);
  if (
    pathWithinRuntime === ".." ||
    pathWithinRuntime.startsWith(`..${sep}`) ||
    isAbsolute(pathWithinRuntime)
  ) {
    throw new Error(`Deployed dependency escapes runtime root: ${label}`);
  }
};
const sourceApp = join(sourceRoot, appPath);
const deployedApp = join(destinationRoot, appPath);
const sourceDist = join(sourceApp, "dist");
if (!(await stat(sourceDist)).isDirectory()) {
  throw new Error(`Build output is missing: ${sourceDist}`);
}

const deployedDist = join(deployedApp, "dist");
await rm(deployedDist, { recursive: true, force: true });
await cp(sourceDist, deployedDist, { recursive: true });

// All compiled workspace imports must continue resolving from the app's
// node_modules. Adding package-local contexts changes Nest dependency tokens.
// pnpm deploy also copies source and tooling unless they are removed here.
const runtimeEntries = new Set(["node_modules", "package.json", "dist"]);
for (const entry of await readdir(deployedApp)) {
  if (runtimeEntries.has(entry)) continue;
  await rm(join(deployedApp, entry), { recursive: true, force: true });
}

// deploy may create multiple Prisma client installations for peer contexts.
// Keep each one paired with the client and native engine generated by the
// builder, rather than relying on install scripts running again during deploy.
const sourceDatabase = join(sourceRoot, "packages/database");
const sourceClientManifestPath = await realpath(
  createRequire(join(sourceDatabase, "package.json")).resolve(
    "@prisma/client/package.json",
  ),
);
const sourceClientManifest = await readManifest(sourceClientManifestPath);
const sourceClientModules = dirname(dirname(dirname(sourceClientManifestPath)));
const generatedClient = join(sourceClientModules, ".prisma/client");
if (!(await stat(generatedClient)).isDirectory()) {
  throw new Error(`Generated Prisma client is missing: ${generatedClient}`);
}
const deployedStore = join(deployedApp, "node_modules/.pnpm");
const clientInstallations = new Set();
for (const entry of await readdir(deployedStore, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const candidate = join(
    deployedStore,
    entry.name,
    "node_modules/@prisma/client/package.json",
  );
  const clientManifestPath = await realpath(candidate).catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  if (!clientManifestPath || clientInstallations.has(clientManifestPath))
    continue;
  const clientManifest = await readManifest(clientManifestPath);
  if (clientManifest.version !== sourceClientManifest.version) {
    throw new Error(
      `Deployed Prisma client version differs: ${clientManifestPath}`,
    );
  }
  clientInstallations.add(clientManifestPath);
  const clientModules = dirname(dirname(dirname(clientManifestPath)));
  assertRuntimePath(clientModules, "@prisma/client");
  const destinationClient = join(clientModules, ".prisma/client");
  await rm(destinationClient, { recursive: true, force: true });
  await cp(generatedClient, destinationClient, { recursive: true });
}
if (clientInstallations.size === 0) {
  throw new Error(
    "Deployed production runtime has no Prisma client installation",
  );
}

if (appPath === "apps/backend") {
  const databaseManifest = await realpath(
    createRequire(join(deployedApp, "package.json")).resolve(
      "@ringee/database/package.json",
    ),
  );
  const databaseModules = dirname(dirname(dirname(databaseManifest)));
  assertRuntimePath(databaseModules, "@ringee/database");
  const deployedDatabase = join(destinationRoot, "packages/database");
  await mkdir(deployedDatabase, { recursive: true });
  await cp(
    join(sourceDatabase, "package.json"),
    join(deployedDatabase, "package.json"),
  );
  await cp(join(sourceDatabase, "prisma"), join(deployedDatabase, "prisma"), {
    recursive: true,
  });
  const databaseModulesLink = join(deployedDatabase, "node_modules");
  await rm(databaseModulesLink, { recursive: true, force: true });
  await symlink(
    relative(deployedDatabase, databaseModules),
    databaseModulesLink,
    "dir",
  );
}

console.log(`Prepared production runtime for ${appPath} at ${destinationRoot}`);
